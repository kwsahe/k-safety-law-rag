def _compact(value: str) -> str:
    return re.sub(r"\s+", "", value)


def is_lithium_battery_fire_scenario(value: str) -> bool:
    compact = _compact(value)
    has_battery = any(term in compact for term in ("리튬전지", "리튬배터리", "일차전지", "이차전지"))
    has_fire = any(term in compact for term in ("화재", "폭발", "발열", "발화", "열폭주"))
    return has_battery and has_fire


def classify_lithium_question(question: str, fact_text: str = "") -> str | None:
    """Return a narrow route only when the active scenario is a lithium fire."""
    if not is_lithium_battery_fire_scenario(f"{question}\n{fact_text}"):
        return None

    compact = _compact(question)
    if any(term in compact for term in ("종합평가", "최종보고서", "보고서형식", "구조적원인")):
        return "lithium_comprehensive"
    if any(term in compact for term in ("도급", "파견", "원청", "하청", "인력공급", "이주노동자")) and any(
        term in compact for term in ("책임", "근거", "판단", "의무")
    ):
        return "lithium_contract_dispatch"
    if any(term in compact for term in ("위험성평가", "전조", "반복", "5차례", "다섯차례")):
        return "lithium_risk_warning"
    if any(term in compact for term in ("다수사망", "23명", "양형", "가중", "처벌수위")):
        return "lithium_mass_fatality_sentencing"
    if any(term in compact for term in ("위험물", "위험물질", "리튬", "안전보건교육", "교육")):
        return "lithium_hazard_training"
    return None


