def _company(fact_text: str) -> str:
    match = re.search(
        r"\(주\)\s*[가-힣A-Za-z0-9]+?(?=의(?:\s|책임)|[\s,\"'}\]])",
        fact_text,
    )
    return re.sub(r"\s+", "", match.group(0)) if match else "해당 사업주"


